#!/usr/bin/env python3
"""Exercise dedicated prediction C handles against exported real fixtures.

These are transport/ownership checks, not a gameplay oracle. Generate inputs
with build/test_combat_prediction <directory>. The fixture executable is a
different process; this controlled same-build test primes the same Cultists
registry and rebinds only runtime_id after checking schema/model IDs.
Production imports still reject foreign IDs.
All calls on one raw handle are serialized, as required by env/c_api.h.
"""
import argparse
import ctypes as c
import json
from pathlib import Path


class Action(c.Structure):
    _fields_ = [(name, c.c_int32) for name in ("kind", "index", "target", "col", "row")]


def check(library: Path, fixtures: Path) -> None:
    lib = c.CDLL(str(library.resolve()))
    pointer = c.c_void_p
    owners: set[int] = set()

    def bind(name, arguments, result):
        method = getattr(lib, "sts2_combat_prediction_" + name)
        method.argtypes, method.restype = arguments, result
        return method

    create = bind("create", [], pointer)
    destroy = bind("destroy", [pointer], None)
    from_game = bind("from_game_snapshot", [pointer, pointer, c.c_size_t, c.POINTER(pointer)], c.c_int)
    restore = bind("import_snapshot", [pointer, pointer, c.c_size_t, c.POINTER(pointer)], c.c_int)
    clone = bind("clone", [pointer, c.POINTER(pointer)], c.c_int)
    predict = bind("predict", [pointer, Action, c.POINTER(pointer)], c.c_int)
    export = bind("export_snapshot", [pointer], c.c_int)
    inspect = bind("inspect_current", [pointer], c.c_int)
    queries = bind("export_queries", [pointer], c.c_int)
    assert not hasattr(lib, "sts2_combat_prediction_export_policy_probe"), "search policy remains in the C ABI"
    calculated = bind("export_calculated_vars", [pointer], c.c_int)
    orbs = bind("export_orbs", [pointer], c.c_int)
    powers = bind("export_power_queries", [pointer], c.c_int)
    legal = bind("legal_actions", [pointer], c.c_int)
    state_hash = bind("hash", [pointer, c.POINTER(c.c_uint64)], c.c_int)
    result = bind("last_result", [pointer], pointer)
    error = bind("last_error", [pointer], c.c_char_p)

    # Prime the exact same encounter registry as the fixture executable. This
    # benchmark run supplies no fields to the imported fixture state. Native
    # validation still checks every model/definition/callback binding.
    lib.sts2_env_create.argtypes, lib.sts2_env_create.restype = [], pointer
    lib.sts2_env_destroy.argtypes, lib.sts2_env_destroy.restype = [pointer], None
    lib.sts2_env_export_blank_template.argtypes, lib.sts2_env_export_blank_template.restype = [pointer], c.c_int
    lib.sts2_env_last_result.argtypes, lib.sts2_env_last_result.restype = [pointer], pointer
    lib.sts2_env_inspect_combat_named.argtypes = [pointer, c.c_char_p, c.c_char_p, c.c_int32, c.c_char_p, c.c_int32]
    lib.sts2_env_inspect_combat_named.restype = c.c_int
    metadata_owner = lib.sts2_env_create()
    assert metadata_owner
    try:
        assert lib.sts2_env_inspect_combat_named(metadata_owner, b"DUAL001", b"IRONCLAD", 0, b"CULTISTS_NORMAL", 0) == 0
        assert lib.sts2_env_export_blank_template(metadata_owner) == 0
        metadata = json.loads(c.string_at(lib.sts2_env_last_result(metadata_owner)))["snapshot"]
    finally:
        lib.sts2_env_destroy(metadata_owner)

    def fixture(name):
        document = json.loads((fixtures / (name + ".json")).read_text())
        inner = document.get("inner_snapshot", document)
        for key in ["schema_sha256", "model_id_hash", "registry_scope"]:
            assert inner[key] == metadata[key], "fixture was generated by another build"
        inner["runtime_id"] = metadata["runtime_id"]
        return json.dumps(document, separators=(",", ":")).encode()

    def own(value):
        assert value and value not in owners, "missing or aliased successor"
        owners.add(value)
        return value

    def ok(status, handle):
        assert status == 0, error(handle).decode()

    def load(method, diagnostic, payload):
        output = pointer(123)  # Every rejected factory must clear this.
        storage = c.create_string_buffer(payload)
        ok(method(diagnostic, storage, len(payload), c.byref(output)), diagnostic)
        return own(output.value)

    def snapshot(handle):
        ok(export(handle), handle)
        return c.string_at(result(handle))

    def hash_of(handle):
        output = c.c_uint64()
        ok(state_hash(handle, c.byref(output)), handle)
        return output.value

    def failed(status, output, handle):
        assert status == -1 and output.value is None and error(handle), "failure contract violated"

    diagnostic = own(create())
    try:
        foreign_payload = (fixtures / "root.json").read_bytes()
        if json.loads(foreign_payload)["runtime_id"] != metadata["runtime_id"]:
            foreign = c.create_string_buffer(foreign_payload)
            output = pointer(123)
            failed(from_game(diagnostic, foreign, len(foreign_payload), c.byref(output)), output, diagnostic)
            assert b"incompatible runtime_id" in error(diagnostic)
        root = load(from_game, diagnostic, fixture("root"))
        baseline, root_hash = snapshot(root), hash_of(root)
        ok(inspect(root), root)
        view = json.loads(c.string_at(result(root)))
        assert (view["prediction_hash"] == root_hash
                and view["state_hash"] == json.loads(baseline)["inner_snapshot"]["state_hash"]
                and view["terminal"] is False and view["root"]["hand"])
        assert hash_of(root) == root_hash and snapshot(root) == baseline
        expected = json.loads(fixture("active"))
        assert json.loads(baseline) == expected
        ok(queries(root), root)
        game_queries = json.loads(c.string_at(result(root)))
        assert (game_queries["format"] == "sts2env.combat_prediction_queries"
                and game_queries["version"] == 4 and game_queries["prediction_hash"] == root_hash
                and game_queries["query_semantics"] == "game"
                and "policy_projection_complete" not in game_queries
                and "threat_projection_complete" not in game_queries)
        assert hash_of(root) == root_hash and snapshot(root) == baseline
        ok(calculated(root), root)
        calculated_vars = json.loads(c.string_at(result(root)))
        assert (calculated_vars["format"] == "sts2env.combat_calculated_vars"
                and calculated_vars["version"] == 2 and calculated_vars["prediction_hash"] == root_hash
                and calculated_vars["query_semantics"] == "game"
                and "policy_projection_complete" not in calculated_vars
                and "prediction_semantics" not in calculated_vars)
        assert hash_of(root) == root_hash and snapshot(root) == baseline

        ok(orbs(root), root)
        orb_values = json.loads(c.string_at(result(root)))
        assert (orb_values["format"] == "sts2env.combat_orb_queries"
                and orb_values["version"] == 2 and orb_values["prediction_hash"] == root_hash
                and "original_state_key_complete" not in orb_values
                and orb_values["query_semantics"] == "game")
        assert hash_of(root) == root_hash and snapshot(root) == baseline

        ok(powers(root), root)
        power_values = json.loads(c.string_at(result(root)))
        assert (power_values["format"] == "sts2env.combat_power_queries"
                and power_values["version"] == 1 and power_values["prediction_hash"] == root_hash
                and power_values["query_semantics"] == "game")
        assert hash_of(root) == root_hash and snapshot(root) == baseline

        # The pointer aliases root.result; the import must copy before clearing
        # diagnostic buffers. Do not convert it into a Python string first.
        ok(export(root), root)
        borrowed, length = result(root), len(baseline)
        output = pointer(123)
        ok(restore(root, borrowed, length, c.byref(output)), root)
        restored = own(output.value)
        assert snapshot(restored) == baseline and hash_of(root) == root_hash

        # Malformed aliased input must fail cleanly and the same source can
        # still export, clone and predict afterwards.
        ok(export(root), root)
        failed(restore(root, result(root), len(baseline) - 1, c.byref(output)), output, root)
        assert hash_of(root) == root_hash
        empty = c.create_string_buffer(b"{}")
        for payload_pointer, size in [(None, 1), (empty, 0), (empty, 4 * 1024 * 1024 + 1)]:
            output = pointer(123)
            failed(restore(root, payload_pointer, size, c.byref(output)), output, root)
        for action in [Action(258, 0, 0, 0, 0), Action(3, -1, -1, 1, 0), Action(2, 9999, -1, 0, 0)]:
            output = pointer(123)
            failed(predict(root, action, c.byref(output)), output, root)
            assert hash_of(root) == root_hash
        output = pointer()
        ok(clone(root, c.byref(output)), root)
        cloned = own(output.value)
        assert snapshot(cloned) == baseline
        ok(powers(cloned), cloned)
        assert json.loads(c.string_at(result(cloned))) == power_values
        ok(predict(root, Action(3, -1, -1, 0, 0), c.byref(output)), root)
        own(output.value)
        assert snapshot(root) == baseline

        unported = c.create_string_buffer(fixture("unported_root"))
        output = pointer(123)
        assert from_game(root, unported, len(unported.value), c.byref(output)) == 1
        assert output.value is None and error(root), "unported root returned an owner or lost its reason"
        assert hash_of(root) == root_hash

        for name in ["victory", "defeat", "choice", "resolved", "choice_lethal", "choice_lethal_selected", "choice_victory", "card_effect"]:
            payload = fixture(name)
            branch = load(restore, diagnostic, payload)
            assert json.loads(snapshot(branch)) == json.loads(payload)
            ok(clone(branch, c.byref(output)), branch)
            sibling = own(output.value)
            assert snapshot(sibling) == snapshot(branch)
            branch_hash = hash_of(branch)
            ok(inspect(branch), branch)
            view = json.loads(c.string_at(result(branch)))
            assert (view["prediction_hash"] == branch_hash
                    and view["terminal"] is (json.loads(payload)["terminal"] is not None)
                    and "root" in view)
            assert hash_of(branch) == branch_hash and json.loads(snapshot(branch)) == json.loads(payload)
            ok(calculated(branch), branch)
            assert json.loads(c.string_at(result(branch)))["prediction_hash"] == branch_hash
            ok(orbs(branch), branch)
            assert json.loads(c.string_at(result(branch)))["prediction_hash"] == branch_hash
            ok(powers(branch), branch)
            assert json.loads(c.string_at(result(branch)))["prediction_hash"] == branch_hash
            assert hash_of(branch) == branch_hash and json.loads(snapshot(branch)) == json.loads(payload)
            ok(legal(branch), branch)
            actions = json.loads(c.string_at(result(branch)))["actions"]
            ok(queries(branch), branch)
            game_queries = json.loads(c.string_at(result(branch)))
            assert game_queries["prediction_hash"] == branch_hash
            assert game_queries["terminal"] is (json.loads(payload)["terminal"] is not None)
            assert game_queries["pending_choice"] is (name in ["choice", "choice_lethal", "choice_lethal_selected"])
            assert hash_of(branch) == branch_hash and json.loads(snapshot(branch)) == json.loads(payload)
            if json.loads(payload)["terminal"] is not None:
                assert actions == []
                output = pointer(123)
                failed(predict(branch, Action(3, -1, -1, 0, 0), c.byref(output)), output, branch)
            elif name in ["choice", "choice_lethal", "choice_lethal_selected"]:
                assert actions and all(item["kind"] == 12 for item in actions)
                selected = actions[0]
                ok(predict(branch, Action(selected["kind"], selected["index"], selected["target"], 0, 0), c.byref(output)), branch)
                answered = own(output.value)
                answer_fixture = {"choice": "resolved", "choice_lethal": "choice_lethal_selected",
                                  "choice_lethal_selected": "choice_victory"}[name]
                assert json.loads(snapshot(answered)) == json.loads(fixture(answer_fixture))
            assert hash_of(branch) == branch_hash

        output = pointer(123)
        failed(clone(diagnostic, c.byref(output)), output, diagnostic)
        assert queries(diagnostic) == -1 and error(diagnostic)
        assert queries(None) == -1
        assert calculated(diagnostic) == -1 and error(diagnostic)
        assert calculated(None) == -1
        assert orbs(diagnostic) == -1 and error(diagnostic)
        assert orbs(None) == -1
        assert powers(diagnostic) == -1 and error(diagnostic)
        assert powers(None) == -1
        assert clone(root, None) == -1 and error(root)
        assert state_hash(root, None) == -1 and error(root)
        output = pointer(123)
        assert clone(None, c.byref(output)) == -1 and output.value is None
        zero_hash = c.c_uint64(123)
        assert state_hash(None, c.byref(zero_hash)) == -1 and zero_hash.value == 0
        destroy(None)
        print("Prediction C ABI checks passed: borrowed buffers, strict input, null-on-failure, independent owners, terminal/choice query scope, card effect facts restore, terminal restore and choice replay.")
    finally:
        for owner in owners:
            destroy(owner)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("fixtures", type=Path)
    parser.add_argument("--library", type=Path, default=Path(__file__).resolve().parents[2] / "build/libsts2env_c.so")
    options = parser.parse_args()
    check(options.library, options.fixtures)
