namespace sts2 {

// What kind of decision the agent is asked for.
enum class ChoiceKind : uint8_t {
    CardSelect,  // CardSelectCmd.*: pick cards from a list
    Bundle,      // CardSelectCmd.FromChooseABundleScreen
    Option,      // a list of labelled options (events, rewards, ...)
};

// Descriptions generated by the original selection call. They do not execute
// an option and are owned by the pending request, outside POD GameState.
enum class ChoiceOptionKind : uint8_t { Card, Bundle, Reward, Alternative, Proceed };
struct ChoiceOption {
    ChoiceOptionKind kind = ChoiceOptionKind::Card;
    std::string key;  // original alternative key, empty when no key is supplied
    std::vector<uint32_t> cards;
    uint32_t reward = 0;
    bool enabled = true;  // stable backend index; removed/disabled UI options are unavailable
};

struct ChoiceRequest {
    ChoiceKind kind = ChoiceKind::Option;
    int32_t option_count = 0;
    int32_t min_select = 1;
    int32_t max_select = 1;
    std::string prompt;  // loc key or a short description, for agents and logs
    // CardSelect: the offered cards (CardRefs), whether the selection may be
    // empty, and the CardSelectCmd method (the oracle's `source`).
    std::vector<uint32_t> cards;
    bool subset = false;  // an ordered subset: answer the count, then each index (CardSelectCmd)
    std::vector<int32_t> selected;  // subset, when asking for an index: the indices answered so far
    bool can_skip = false;
    std::string source;
    // One entry for every offered option, in original order. A subset count
    // question still describes the cards; its legal answers are counts.
    std::vector<ChoiceOption> options;
};

// Thrown when execution needs a decision that the prefix does not contain.
// The environment rolls back to its snapshot, asks the agent, and re-runs the
// step with the answer appended.
struct NeedChoice {
    ChoiceRequest request;
};

enum class ExecutionBoundaryKind : uint8_t {
    EnemyPhaseDone = 0,
    SafeOutcome = 1,
};

constexpr uint8_t execution_boundary_bit(ExecutionBoundaryKind kind) {
    return static_cast<uint8_t>(1u << static_cast<uint8_t>(kind));
}

// Thrown at a requested, safe execution boundary. The ordinal is one-based
// among all requested boundary kinds encountered by this Sim execution.
struct NeedBoundary {
    ExecutionBoundaryKind kind;
    uint64_t ordinal;
};

class Sim {
public:
    explicit Sim(GameState& state) : g(&state) {}

    GameState* g;
    // Borrowed only while a prediction transition (or choice replay) executes.
    // Every newly constructed Sim, including an Env clone, starts unscoped.
    ExecutionTrace* execution_trace = nullptr;
    ExecutionDamageSourceKind damage_source_kind = ExecutionDamageSourceKind::Unknown;
    std::string damage_source_id;

    // Boundary requests are transient execution controls, not game state.
    // Configure once for an action/replay; the skip count is the number of
    // matching checkpoints to pass before the next one throws NeedBoundary.
    void ConfigureExecutionBoundaries(uint8_t requested_mask, uint64_t skip_ordinal) {
        requested_boundary_mask_ = requested_mask;
        boundary_skip_ordinal_ = skip_ordinal;
        boundary_ordinal_ = 0;
    }

    bool ExecutionBoundaryRequested(ExecutionBoundaryKind kind) const {
        return (requested_boundary_mask_ & execution_boundary_bit(kind)) != 0;
    }

    void CheckpointExecutionBoundary(ExecutionBoundaryKind kind) {
        if (!ExecutionBoundaryRequested(kind)) return;
        const uint64_t ordinal = ++boundary_ordinal_;
        if (ordinal > boundary_skip_ordinal_) throw NeedBoundary{kind, ordinal};
    }

    // Answers already given for the step being executed, in order.
    void set_prefix(std::span<const int32_t> answers) {
        prefix_ = answers;
        cursor_ = 0;
    }
    bool prefix_consumed() const { return cursor_ == prefix_.size(); }

    // One answer: an option index, a selection count or a card index, as the
    // caller defines for its request.
    int32_t Choose(const ChoiceRequest& request) {
        if (cursor_ < prefix_.size()) {
            const int32_t answer = prefix_[cursor_++];
            // A restored prefix must obey the same UI availability as a fresh
            // Answer. Selection counts are not option indices.
            if (!(request.subset && request.prompt == "count") && answer >= 0
                && static_cast<size_t>(answer) < request.options.size()
                && !request.options[static_cast<size_t>(answer)].enabled)
                throw InvalidRequest("choice: option is unavailable at this prefix");
            return answer;
        }
        throw NeedChoice{request};
    }

private:
    std::span<const int32_t> prefix_;
    size_t cursor_ = 0;
    uint8_t requested_boundary_mask_ = 0;
    uint64_t boundary_skip_ordinal_ = 0;
    uint64_t boundary_ordinal_ = 0;
};

class ExecutionSourceScope {
public:
    ExecutionSourceScope(Sim& sim, ExecutionDamageSourceKind kind, std::string_view id, std::string_view operation = "effect")
        : sim_(sim), previous_kind_(sim.damage_source_kind), previous_id_(sim.damage_source_id) {
        if (sim.execution_trace) {
            std::string next_id(id);
            trace_=sim.execution_trace;uncaught_=std::uncaught_exceptions();
            frame_=trace_->Enter(operation, kind, id);
            sim.damage_source_kind = kind;
            sim.damage_source_id = std::move(next_id);
        }
    }
    ~ExecutionSourceScope() {
        if(trace_) trace_->Leave(frame_,std::uncaught_exceptions()>uncaught_);
        sim_.damage_source_kind = previous_kind_;
        sim_.damage_source_id = std::move(previous_id_);
    }
    ExecutionSourceScope(const ExecutionSourceScope&) = delete;
    ExecutionSourceScope& operator=(const ExecutionSourceScope&) = delete;
private:
    Sim& sim_;
    ExecutionDamageSourceKind previous_kind_;
    std::string previous_id_;
    ExecutionTrace* trace_=nullptr;
    int32_t frame_=-1;
    int uncaught_=0;
};

class ExecutionTraceScope {
public:
    ExecutionTraceScope(Sim& sim, ExecutionTrace* trace)
        : sim_(sim), previous_(sim.execution_trace), rng_observer_(sim,trace) {
        sim_.execution_trace = trace;
    }
    ~ExecutionTraceScope() { sim_.execution_trace = previous_; }
    ExecutionTraceScope(const ExecutionTraceScope&) = delete;
    ExecutionTraceScope& operator=(const ExecutionTraceScope&) = delete;
private:
    Sim& sim_;
    ExecutionTrace* previous_;
    RngExecutionObserver rng_observer_;
};

}  // namespace sts2
