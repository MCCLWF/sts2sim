#!/usr/bin/env python3
"""Translate the pinned upstream constant declarations without retyping their values."""
import argparse
import hashlib
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "external/CombatSolver/src/Search/SolverWeights.cs"
TARGET = ROOT / "search/combatsolver/weights.generated.h"


def generate():
    source = SOURCE.read_text()
    fields = re.findall(r"public const (int|double) (\w+) = ([^;]+);", source)
    if not fields:
        raise ValueError("upstream SolverWeights declarations not found")
    lines = ["// Generated by tools/combatsolver/gen_weights.py; do not edit.",
             "// CombatSolver 0.47.3; see THIRD_PARTY_NOTICES.md and LICENSE.",
             "// Source SHA256: " + hashlib.sha256(source.encode()).hexdigest(),
             "#pragma once", "#include <cstdint>", "",
             "namespace sts2::combatsolver {", "struct SolverWeights {"]
    for kind, name, expression in fields:
        expression = re.sub(r"(?<=\d)_(?=\d)", "", expression)
        expression = re.sub(r"(?<=\d)d\b", "", expression)
        if not re.fullmatch(r"[\w\s+*/().-]+", expression):
            raise ValueError("unsupported expression: " + expression)
        lines.append(f"    static constexpr {'int32_t' if kind == 'int' else 'double'} {name} = {expression};")
    lines += ["};", "}  // namespace sts2::combatsolver", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if TARGET.read_text() != generated:
            raise SystemExit("CombatSolver constants differ from pinned source; regenerate")
        print("CombatSolver weights match pinned source")
    else:
        TARGET.write_text(generated)
