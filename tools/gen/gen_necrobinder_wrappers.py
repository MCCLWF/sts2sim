#!/usr/bin/env python3
"""Generate thin per-model wrappers for the v0.111.0 Necrobinder model graph.

Effects live in hand-reviewed C++ translation units. These wrappers expose
only members that the original model overrides and route them to the matching
content-specific effect dispatcher. `gen_dispatch.py` then checks every
original override against the declarations here.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MODELS = os.path.join(ROOT, "game", "Models")
CONTENT = os.path.join(ROOT, "data", "content.json")
sys.path.insert(0, os.path.join(ROOT, "tools", "gen"))
import gen_dispatch  # noqa: E402


def split_args(text):
    result, depth, cur = [], 0, ""
    for ch in text:
        if ch in "({[<":
            depth += 1
        elif ch in ")}]>":
            depth -= 1
        if ch == "," and depth == 0:
            result.append(cur.strip())
            cur = ""
        else:
            cur += ch
    result.append(cur.strip())
    return result


def read_members(filename):
    result = {}
    path = os.path.join(MODELS, filename + ".def")
    for line in open(path, encoding="utf-8"):
        match = re.match(r"SIM_MEMBER(?:_CUSTOM)?\((.*)\)\s*$", line.strip())
        if not match:
            continue
        base, ret, name, params, args, _default = split_args(match.group(1))
        result[(base, name)] = (ret, params, args)
    return result


def classes_in(folder, ignored_header):
    found = set()
    path = os.path.join(MODELS, folder)
    for filename in os.listdir(path):
        if not filename.endswith(".h") or filename == ignored_header:
            continue
        text = open(os.path.join(path, filename), encoding="utf-8").read()
        found.update(re.findall(r"^(?:struct|class) (\w+)\s*:", text, re.M))
    return found


def model_id_for_type(models, kind, class_name):
    return next((m["id"] for m in models if m["kind"] == kind and
                 m["type"].split(".")[-1] == class_name), None)


def power_targets(models, card_ids):
    by_id = {m["id"]: m for m in models}
    targets = set()
    for card_id in card_ids:
        model = by_id[card_id]
        path = os.path.join(gen_dispatch.SRC, model["source"])
        text = open(path, encoding="utf-8").read()
        targets.update(re.findall(r"PowerCmd\.[A-Za-z0-9_]+<([A-Za-z0-9_]+)>", text))
    return targets


def get_helper_methods(model, members, source):
    out = []
    for override in model.get("overrides", []):
        member = override.split(" (via", 1)[0]
        if "." not in member:
            continue
        base, name = member.split(".", 1)
        method_name = name[4:] if name.startswith("get_") else name
        if base == "CardModel" and method_name == "OnUpgrade" and gen_dispatch.delta_only_on_upgrade(source):
            continue
        signature = members.get((base, method_name))
        if signature is None:
            continue
        out.append((base, method_name, *signature))
    return out


def render_group(path, kind, base, folder, ids, content_models, members, ignored):
    existing = classes_in(folder, os.path.basename(path))
    output = ["// GENERATED by tools/gen/gen_necrobinder_wrappers.py. Do not edit.",
              "#pragma once", "", '#include "game/All.h"', f'#include "game/Models/{base}.h"', "",
              "namespace sts2 {", f"namespace Necrobinder{base[:-5] if base.endswith('Model') else base}Effects {{"]
    declarations = set()
    model_rows = []
    by_id = {m["id"]: m for m in content_models}
    for model_id in ids:
        model = by_id.get(model_id)
        if model is None:
            continue
        cls = model["type"].split(".")[-1]
        if cls in existing or cls in ignored:
            continue
        helpers = get_helper_methods(model, members, model.get("source", ""))
        if not helpers:
            continue
        model_rows.append((cls, helpers))
        for _member_base, name, ret, params, args in helpers:
            params_inner = params[1:-1].strip()
            call_args = args[1:-1].strip()
            args_suffix = (", " + params_inner) if params_inner else ""
            declarations.add(f"{ret} {name}({base} model{args_suffix});")
    output.extend("    " + item for item in sorted(declarations))
    output.extend(["}", ""])
    for cls, helpers in model_rows:
        output.append(f"struct {cls} : {base} {{")
        output.append(f"    SIM_MODEL({cls}, {base})")
        for _member_base, name, ret, params, args in helpers:
            params_inner = params[1:-1].strip()
            call_args = args[1:-1].strip()
            signature = f"{ret} {name}({params_inner}) const" if params_inner else f"{ret} {name}() const"
            helper_args = f"*this{', ' + call_args if call_args else ''}"
            body = f"Necrobinder{base[:-5] if base.endswith('Model') else base}Effects::{name}({helper_args})"
            statement = f"{signature} {{ "
            statement += f"return {body};" if ret != "void" else f"{body};"
            statement += " }"
            output.append("    " + statement)
        output.extend(["};", ""])
    output.extend(["}  // namespace sts2", ""])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as file:
        file.write("\n".join(output))
    print(f"{path}: generated {len(model_rows)} {kind} wrappers")


def main():
    content_models = json.load(open(CONTENT, encoding="utf-8"))["models"]
    by_id = {m["id"]: m for m in content_models}
    cards = by_id["CARD_POOL.NECROBINDER_CARD_POOL"]["props"]["AllCardIds"]
    relics = by_id["RELIC_POOL.NECROBINDER_RELIC_POOL"]["props"]["AllRelicIds"]
    related_cards = cards + ["CARD.SOUL", "CARD.SWEEPING_GAZE"]
    powers = sorted(power_targets(content_models, cards))

    abstract = read_members("AbstractModel")
    card_members = read_members("CardModel")
    power_members = read_members("PowerModel")
    relic_members = read_members("RelicModel")

    render_group(os.path.join(MODELS, "Cards", "NecrobinderCards.h"), "card", "CardModel", "Cards",
                 related_cards, content_models, {**abstract, **card_members}, set())
    render_group(os.path.join(MODELS, "Powers", "NecrobinderPowers.h"), "power", "PowerModel", "Powers",
                 ["POWER." + re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper() for name in powers],
                 content_models, {**abstract, **power_members}, {"DoomPower"})
    render_group(os.path.join(MODELS, "Relics", "NecrobinderRelics.h"), "relic", "RelicModel", "Relics",
                 relics, content_models, {**abstract, **relic_members}, set())


if __name__ == "__main__":
    main()
