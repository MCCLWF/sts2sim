"""Generate field traversal for the restricted POD state declaration grammar.

This is deliberately not a general C++ parser. Unknown declarations fail the
build; fields cannot silently drop out of state hashing when the schema grows.
"""
from pathlib import Path
import argparse
import re
import hashlib

ROOT = Path(__file__).resolve().parents[2]
HEADERS = ("engine/map.h", "engine/run_state.h", "engine/sim/state.h")
SCHEMA_INPUTS = HEADERS + ("engine/containers.h", "engine/small_vec.h", "engine/sim/pool.h",
                          "core/dec.h", "core/rng.h", "content/generated/ids.h",
                          "content/generated/enums.h", "engine/sim/sim.h", "env/env.h", "env/operation.h")


def balanced_end(text, start, opening="{", closing="}"):
    depth = 1
    for i in range(start + 1, len(text)):
        depth += (text[i] == opening) - (text[i] == closing)
        if depth == 0:
            return i
    raise ValueError("unterminated declaration")


def declarators(text):
    parts, start, stack = [], 0, []
    pairs = {">": "<", "]": "[", ")": "(", "}": "{"}
    for i, char in enumerate(text):
        if char in "<([{":
            stack.append(char)
        elif char in pairs:
            if not stack or stack.pop() != pairs[char]:
                raise ValueError(f"unsupported declaration: {text}")
        elif char == "," and not stack:
            parts.append(text[start:i])
            start = i + 1
    return parts + [text[start:]]


def parse_struct(name, body, structs):
    fields, pos = [], 0
    while pos < len(body):
        while pos < len(body) and body[pos].isspace():
            pos += 1
        if pos == len(body):
            break
        nested = re.match(r"struct\s+(\w+)\s*\{", body[pos:])
        if nested:
            begin = pos + nested.end() - 1
            end = balanced_end(body, begin)
            parse_struct(f"{name}::{nested[1]}", body[begin + 1:end], structs)
            pos = end + 1
            while pos < len(body) and body[pos].isspace():
                pos += 1
            if body[pos:pos + 1] != ";":
                raise ValueError(f"unsupported nested struct in {name}")
            pos += 1
            continue
        start = pos
        is_method = False
        while pos < len(body):
            char = body[pos]
            prefix = body[start:pos]
            if char == "(" and "=" not in prefix:
                is_method = True
            if char == "{":
                end = balanced_end(body, pos)
                if is_method:
                    pos = end + 1
                    break
                pos = end
            elif char == ";":
                declaration = body[start:pos].strip()
                pos += 1
                if is_method or declaration.startswith(("friend ", "static ", "static_assert")):
                    break
                if not declaration:
                    break
                for index, part in enumerate(declarators(declaration)):
                    lhs = re.split(r"=|\{", part, maxsplit=1)[0].strip()
                    field = re.search(r"\b([A-Za-z_]\w*)\s*(?:\[[^\]]*\]\s*)*$", lhs)
                    if field is None or (index == 0 and not lhs[:field.start()].strip()):
                        raise ValueError(f"unsupported field in {name}: {declaration}")
                    fields.append(field[1])
                break
            pos += 1
        else:
            raise ValueError(f"unsupported trailing declaration in {name}: {body[start:]}")
    structs.append((name, fields))


def generate():
    structs = []
    for path in HEADERS:
        text = (ROOT / path).read_text()
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
        pos = 0
        while match := re.search(r"\bstruct\s+(\w+)\s*\{", text[pos:]):
            begin = pos + match.end() - 1
            end = balanced_end(text, begin)
            parse_struct(match[1], text[begin + 1:end], structs)
            pos = end + 1
    lines = ["// Generated by tools/gen/gen_state_fields.py; do not edit.",
             "#pragma once", '#include "engine/sim/state.h"', "namespace sts2 {"]
    schema = hashlib.sha256()
    for path in SCHEMA_INPUTS:
        schema.update(path.encode() + b"\0" + (ROOT / path).read_bytes() + b"\0")
    lines.append(f'inline constexpr char kStateSchemaSha256[] = "{schema.hexdigest()}";')
    for name, fields in structs:
        lines.append(f"template<class V> inline void visit_state_fields(const {name}& s, V&& visit) {{")
        lines.extend(f"    visit(s.{field});" for field in fields)
        lines.append("}")
        lines.append(f"template<class V> inline void visit_named_state_fields(const {name}& s, V&& visit) {{")
        lines.extend(f'    visit("{field}", s.{field});' for field in fields)
        lines.append("}")
        lines.append(f"template<class V> inline void visit_named_state_fields({name}& s, V&& visit) {{")
        lines.extend(f'    visit("{field}", s.{field});' for field in fields)
        lines.append("}")
    # Flags may legally contain combinations not present in name(enum)'s switch.
    enum_text = (ROOT / "content/generated/enums.h").read_text()
    for match in re.finditer(r"//[^\n]*\[Flags\]\s*enum class (\w+)\s*:\s*(\w+)\s*\{([^}]+)\}", enum_text):
        name, underlying, body = match.groups()
        members = re.findall(r"^\s*(\w+)\s*=", body, flags=re.M)
        lines.append(f"inline bool valid_snapshot_flags({name} v) {{")
        mask = " | ".join(f"static_cast<{underlying}>({name}::{member})" for member in members)
        lines.append(f"    return (static_cast<{underlying}>(v) & ~({mask})) == 0;")
        lines.append("}")
    lines.append("}  // namespace sts2")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "engine/sim/state_fields.generated.h"
    content = generate()
    if args.check:
        if not output.exists() or output.read_text() != content:
            raise SystemExit("POD field schema changed; run tools/gen/gen_state_fields.py")
    else:
        output.write_text(content)


if __name__ == "__main__":
    main()
