// LiveFieldInventory <game data dir> : writes the inventory JSON to stdout.
//
// content.json's "fields" (tools/Sts2Exporter) only has private leaf-typed
// fields. A live model also carries references, collections and compiler
// backing fields, and powers keep their mutable state in a nested Data class.
// All of them are listed here, keyed like content.json's "type".
using System.Reflection;
using System.Runtime.Loader;
using System.Text.Json;
using System.Text.Json.Nodes;

string gameData = args.Length > 0 ? args[0] : typeof(Program).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
    .First(attribute => attribute.Key == "Sts2GameData").Value!;
AssemblyLoadContext.Default.Resolving += (context, name) =>
{
    string path = Path.Combine(gameData, name.Name + ".dll");
    return File.Exists(path) ? context.LoadFromAssemblyPath(path) : null;
};
Assembly game = AssemblyLoadContext.Default.LoadFromAssemblyPath(Path.Combine(gameData, "sts2.dll"));
const string Models = "MegaCrit.Sts2.Core.Models.";
const BindingFlags Declared = BindingFlags.DeclaredOnly | BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic;
string[] bases = ["RelicModel", "PowerModel", "MonsterModel", "CardModel", "PotionModel", "OrbModel",
    "EncounterModel", "EnchantmentModel", "AfflictionModel"];

string Name(Type type) => type.IsGenericType
    ? type.Name.Split('`')[0] + "<" + string.Join(",", type.GetGenericArguments().Select(Name)) + ">"
    : type.Name;

JsonObject categories = new();
foreach (string baseName in bases)
{
    Type baseType = game.GetType(Models + baseName) ?? throw new InvalidOperationException("missing " + baseName);
    JsonObject category = new();
    foreach (Type type in game.GetTypes().Where(type => !type.IsAbstract && baseType.IsAssignableFrom(type))
                 .OrderBy(type => type.FullName, StringComparer.Ordinal))
    {
        JsonArray fields = new();
        for (Type? current = type; current is not null && current != baseType; current = current.BaseType)
            foreach (FieldInfo field in current.GetFields(Declared).OrderBy(field => field.MetadataToken))
                fields.Add(new JsonObject
                {
                    // The same key the bridge derives from a live instance.
                    ["name"] = current == type ? field.Name : current.Name + "." + field.Name,
                    ["type"] = Name(field.FieldType),
                });
        JsonArray data = new();
        // PowerModel.InitInternalData: the nested Data class of a power.
        if (type.GetNestedType("Data", BindingFlags.Public | BindingFlags.NonPublic) is { } nested)
            foreach (FieldInfo field in nested.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic)
                         .OrderBy(field => field.MetadataToken))
                data.Add(new JsonObject { ["name"] = field.Name, ["type"] = Name(field.FieldType) });
        if (fields.Count == 0 && data.Count == 0) continue;
        JsonObject entry = new() { ["fields"] = fields };
        if (data.Count != 0) entry["data"] = data;
        category[type.FullName![Models.Length..]] = entry;
    }
    categories[baseName] = category;
}
Console.WriteLine(new JsonObject
{
    ["format"] = "sts2sim.live_field_inventory", ["version"] = 1,
    ["note"] = "GENERATED by tools/LiveFieldInventory from sts2.dll. Do not edit.",
    ["models"] = categories,
}.ToJsonString(new JsonSerializerOptions { WriteIndented = true }));
